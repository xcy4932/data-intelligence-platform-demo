type ConnectorAuthType = DataConnectorDefinition['authType']

interface PasswordConnectorSeed {
  connectorType: string
  connectorName: string
  connectorCategory: DataConnectorCategory
  categoryName: string
  description: string
  tags: string[]
  defaultPort: number
  supportsOneClickIngest?: boolean
  requiresAuth?: boolean
  authType?: ConnectorAuthType
  recommended?: boolean
  realtime?: boolean
  extraFields?: ConnectorFieldSchema[]
}

function passwordConnectorFields(defaultPort: number, extraFields: ConnectorFieldSchema[] = []): ConnectorFieldSchema[] {
  return [
    ...passwordAuthFields.map((field) =>
      field.key === 'port' ? { ...field, defaultValue: defaultPort } : field,
    ),
    {
      key: 'schema',
      label: 'Schema',
      fieldType: 'input',
      section: 'CONNECTION',
    },
    {
      key: 'catalog',
      label: 'Catalog',
      fieldType: 'input',
      section: 'CONNECTION',
    },
    ...extraFields,
    {
      key: 'jdbcParams',
      label: 'JDBC 参数',
      fieldType: 'keyValue',
      defaultValue: [{ key: 'useUnicode', value: 'true' }],
      section: 'ADVANCED',
    },
    {
      key: 'queryTimeout',
      label: '查询超时秒数',
      fieldType: 'number',
      defaultValue: 60,
      section: 'ADVANCED',
    },
    {
      key: 'maxPreviewRows',
      label: '最大预览行数',
      fieldType: 'number',
      defaultValue: 100,
      section: 'ADVANCED',
    },
    {
      key: 'timezone',
      label: '时区',
      fieldType: 'select',
      defaultValue: 'UTC+8',
      options: [
        { label: 'UTC+8 北京时间', value: 'UTC+8' },
        { label: 'UTC+0', value: 'UTC+0' },
        { label: 'UTC+1 欧洲中部时间', value: 'UTC+1' },
      ],
      section: 'ADVANCED',
    },
  ]
}

function createPasswordConnector(seed: PasswordConnectorSeed): DataConnectorDefinition {
  return {
    connectorType: seed.connectorType,
    connectorName: seed.connectorName,
    connectorCategory: seed.connectorCategory,
    categoryName: seed.categoryName,
    description: seed.description,
    tags: seed.tags,
    supportsTest: true,
    supportsPreview: true,
    supportsOneClickIngest: seed.supportsOneClickIngest ?? false,
    requiresAuth: seed.requiresAuth ?? false,
    authType: seed.authType ?? 'PASSWORD',
    enabled: true,
    recommended: seed.recommended,
    realtime: seed.realtime,
    fields: passwordConnectorFields(seed.defaultPort, seed.extraFields),
  }
}

