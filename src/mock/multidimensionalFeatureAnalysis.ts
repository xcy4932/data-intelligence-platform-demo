function combo(
  reportId: string,
  index: number,
  items: Array<[string, string]>,
  precisionRate: number,
  recallRate: number,
  positiveHitCount: number,
  negativeHitCount: number,
  expandedCount: number,
): MultiDimFeatureCombo {
  const comboItems = items.map(([tagId, value]) => {
    const tag = getMockTag(tagId)
    return {
      tagId: tag.id,
      tagName: tag.name,
      tagValue: value,
      directory: tag.directory,
      tagType: tag.tagType,
      permission: tag.permission,
    }
  })
  return {
    id: `combo-${reportId}-${index}`,
    reportId,
    comboItems,
    score: Number((precisionRate * 0.8 + recallRate * 0.2).toFixed(4)),
    precisionRate,
    recallRate,
    positiveHitCount,
    negativeHitCount,
    expandedCount,
    rankNo: index,
  }
}

