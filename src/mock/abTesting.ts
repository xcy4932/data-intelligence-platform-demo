function createMetricResultForExperiment(experimentId: string, seed: ReportMetricSeed): MetricStatisticResult | null {
  const metric = abMetrics.find((item) => item.id === seed.metricId)
  const variants = abExperimentVariants.filter((variant) => variant.experimentId === experimentId)
  const baselineVariant = variants.find((variant) => variant.isControl) ?? variants[0]
  if (!metric || !baselineVariant) return null
  const sampleSize = seed.sampleSize ?? 24000
  return {
    metricId: metric.id,
    metricName: metric.name,
    metricType: metric.metricCategory,
    versionResults: variants.map((variant, index) => {
      const isBaseline = variant.id === baselineVariant.id || (!baselineVariant.isControl && index === 0)
      const metricValue = isBaseline
        ? seed.baselineValue
        : seed.treatmentValues?.[variant.id] ?? Number((seed.baselineValue * (1.04 + index * 0.015)).toFixed(4))
      const diffAbs = isBaseline ? null : Number((metricValue - seed.baselineValue).toFixed(4))
      const diffRel = diffAbs === null ? null : Number((diffAbs / seed.baselineValue).toFixed(4))
      const pValue = isBaseline ? null : Number(Math.min(0.95, (seed.pValue ?? 0.035) + Math.max(0, index - 1) * 0.018).toFixed(3))
      return {
        versionId: variant.id,
        sampleSize: Math.max(1000, Math.round(sampleSize * (variant.trafficRatio / (baselineVariant.trafficRatio || 50)))),
        metricValue,
        diffAbs,
        diffRel,
        pValue,
        mde: isBaseline ? null : seed.mde ?? 0.02,
        confidenceInterval: isBaseline || diffRel === null ? null : [Number((diffRel - 0.032).toFixed(4)), Number((diffRel + 0.034).toFixed(4))],
        significance: isBaseline ? 'baseline' : pValue !== null && pValue <= 0.05 && diffAbs !== null && diffAbs > 0 ? 'positive' : 'neutral',
      }
    }),
  }
}

function createReportOverview(experiment: Experiment): ExperimentReportOverview {
  const versions = abExperimentVariants
    .filter((variant) => variant.experimentId === experiment.id)
    .map((variant) => ({ versionId: variant.id, versionName: variant.name, isControl: variant.isControl }))
  const coreMetricResults = (reportMetricSeeds[experiment.id] ?? [])
    .map((seed) => createMetricResultForExperiment(experiment.id, seed))
    .filter((result): result is MetricStatisticResult => Boolean(result))
  const firstMetric = coreMetricResults[0]
  const bestResult = firstMetric?.versionResults.find((result) => result.significance === 'positive')
  const bestLift = bestResult?.diffRel ? `${Number((bestResult.diffRel * 100).toFixed(1))}%` : '稳定'
  return {
    experimentId: experiment.id,
    experimentName: experiment.name,
    experimentType: experiment.type,
    status: experiment.status,
    startTime: experiment.startedAt ?? experiment.createdAt,
    endTime: experiment.endedAt ?? null,
    trafficRatio: experiment.trafficRatio,
    confidenceLevel: 0.95,
    dataUpdatedAt: '2026-05-28T00:30:00+02:00',
    conclusionStatus: bestResult ? 'positive' : 'neutral',
    conclusionText: bestResult
      ? `核心指标${firstMetric?.metricName ?? ''}表现稳定正向，当前最佳版本相对对照提升 ${bestLift}。`
      : '当前核心指标表现稳定，建议继续观察完整周期数据。',
    recommendation: bestResult
      ? '建议保持当前实验并进入扩量评估，继续关注护栏指标和分层人群表现。'
      : '建议继续运行至计划样本量，再结合业务成本做上线判断。',
    versions,
    entryUsers: firstMetric?.versionResults.reduce((sum, result) => sum + result.sampleSize, 0) ?? 0,
    coreMetricResults,
  }
}

