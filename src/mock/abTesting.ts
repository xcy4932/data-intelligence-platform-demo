function createMetricBindingSnapshots(experiment: Experiment): MetricBindingSnapshot[] {
  const snapshots: MetricBindingSnapshot[] = []
  experiment.metricIds.forEach((metricId, index) => {
    const metric = abMetrics.find((item) => item.id === metricId)
    if (!metric) return
    const group = abMetricGroups.find((item) => item.id === metric.metricGroupId)
    snapshots.push({
      id: `snap_${experiment.id}_${metricId}`,
      experimentId: experiment.id,
      metricId,
      metricGroupId: metric.metricGroupId,
      metricName: metric.name,
      metricGroupName: group?.name ?? '默认指标组',
      metricRole: index === 0 ? 'core' : 'focus',
      metricCategory: metric.metricCategory,
      definition: JSON.parse(JSON.stringify(metric.definition)),
      numberFormat: metric.numberFormat,
      flexibleValues: [],
      statusAtBinding: metric.status,
      snapshotVersion: 1,
      source: 'experiment_create',
      capturedAt: experiment.createdAt,
    })
  })
  return snapshots
}

